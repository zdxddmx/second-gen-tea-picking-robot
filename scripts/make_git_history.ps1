#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Build the project's Git history as a sequence of meaningful commits.

.DESCRIPTION
    A repository whose entire content arrives in one "initial commit" tells a
    reviewer nothing about how the work was done, and it removes the single most
    useful thing a Git history provides: the ability to see how a module evolved.

    This script replays the finished tree as the sequence of commits it would
    have been built in, which is what the project's own development method
    prescribes (see README "Roadmap" / docs).  Each commit is a coherent unit:
    it adds one layer or one capability, and its message says what and why.

    It is idempotent in the sense that it refuses to run on a repository that
    already has commits, so re-running it cannot corrupt an existing history.

.PARAMETER DryRun
    Print the commit plan without touching the repository.
#>
[CmdletBinding()]
param(
    [switch]$DryRun
)

