# --- guard: refuse to run on a repository that already has commits ---------
if (Test-Path .git) {
    $existing = git rev-list --count HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and [int]$existing -gt 0) {
        throw "this repository already has $existing commit(s); refusing to rewrite history"
    }
} elseif (-not $DryRun) {
    git init -q
    git branch -M main 2>$null
    Write-Host 'initialised an empty repository' -ForegroundColor Green
}

$n = 0
foreach ($entry in $plan) {
    $n++
    $subject = $entry.Title
    Write-Host ("[{0,2}/{1}] {2}" -f $n, $plan.Count, $subject) -ForegroundColor Cyan

    if ($DryRun) { continue }

    foreach ($path in $entry.Paths) {
        if (Test-Path $path) {
            git add -- $path
        } else {
            Write-Warning "  path not found, skipped: $path"
        }
    }

    $staged = git diff --cached --name-only
    if (-not $staged) {
        Write-Warning '  nothing staged; skipping commit'
        continue
    }

    $message = $subject + "`n`n" + $entry.Body.TrimEnd() + "`n"
    $tmp = Join-Path $env:TEMP 'tp_commit_msg.txt'
    # Git wants LF line endings in a commit message file.
    ($message -replace "`r`n", "`n") | Set-Content -Path $tmp -Encoding utf8 -NoNewline
    git commit -q --file $tmp
    if ($LASTEXITCODE -ne 0) { throw "commit failed for: $subject" }
}

if (-not $DryRun) {
    # Anything not covered by the plan (scratch files, generated data) should be
    # either ignored or committed deliberately - never swept in by `git add .`.
    $leftover = git status --porcelain
    if ($leftover) {
        Write-Host ''
        Write-Host 'Uncommitted paths remain (expected: build outputs and generated data):' -ForegroundColor Yellow
        $leftover | ForEach-Object { Write-Host "  $_" }
    }

    Write-Host ''
    Write-Host '--- history ---' -ForegroundColor Green
    git --no-pager log --oneline --decorate
    Write-Host ''
    git --no-pager log --oneline | Measure-Object -Line |
        ForEach-Object { Write-Host ("{0} commits" -f $_.Lines) -ForegroundColor Green }
}

Pop-Location
